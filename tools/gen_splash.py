"""BFMXR's start-up animation and sound, as C data (app/splash_data.h), from a GIF and a WAV.

  tools/gen_splash.py app/assets/splash.gif app/assets/splash.wav app/splash_data.h [--seconds 1.5] [--fps 25]

The video: the GIF's first SECONDS, at FPS (frames picked by the GIF's own timing), scaled to the screen's width
(240 x height kept in proportion), one palette of 32 colours for every frame. A pixel keeps its colour from the
frame before unless it changed by more than THRESHOLD (RGB sum): the GIF's dither jitter is dropped, its motion
kept. Each frame is stored as its difference from the one before (XOR of the colour indices, mostly zeros), LZ4
block-compressed (base/tools/lz4blk.py; app.c has the decoder).
The sound: mono (the channels' mean), resampled to 44.1 kHz, signed 16-bit."""
import argparse
import sys
import wave
from pathlib import Path

import numpy as np
from PIL import Image, ImageSequence

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "base" / "tools"))
import lz4blk  # noqa: E402

THRESHOLD = 70
NCOL = 32
W = 240


def frames(gif, seconds, fps):
    im = Image.open(gif)
    src, t, times = [], 0, []
    for f in ImageSequence.Iterator(im):
        src.append(f.convert("RGB"))
        times.append(t)
        t += f.info.get("duration", 100) or 100
    n = int(round(seconds * fps))
    out = []
    for k in range(n):                              # the frame showing at each tick
        ms = k * 1000.0 / fps
        i = max(j for j, s in enumerate(times) if s <= ms) if ms < t else len(src) - 1
        out.append(src[i])
    h = int(round(im.size[1] * W / im.size[0]))
    return [np.asarray(f.resize((W, h), Image.BOX), dtype=np.int32) for f in out], h


def stabilise(fr):
    out = [fr[0].copy()]
    for f in fr[1:]:
        p = out[-1]
        moved = np.abs(f - p).sum(axis=2, keepdims=True) > THRESHOLD
        out.append(np.where(moved, f, p))
    return out


def sound(path):
    w = wave.open(str(path))
    ch, sw, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    raw = w.readframes(n)
    if sw == 2:
        x = np.frombuffer(raw, dtype="<i2").astype(np.float64)
    elif sw == 1:
        x = (np.frombuffer(raw, dtype=np.uint8).astype(np.float64) - 128) * 256
    elif sw == 3:
        b = np.frombuffer(raw, dtype=np.uint8).reshape(-1, 3).astype(np.int32)
        x = ((b[:, 0] | b[:, 1] << 8 | b[:, 2] << 16) << 8 >> 8).astype(np.float64) / 256
    else:
        raise SystemExit(f"{path}: {8 * sw}-bit samples: 8, 16 or 24 only")
    x = x.reshape(-1, ch).mean(axis=1)
    if rate != 44100:                               # band-limit, then resample (linear between samples)
        if rate > 44100:
            k = np.hanning(9)
            x = np.convolve(x, k / k.sum(), mode="same")
        m = int(round(len(x) * 44100 / rate))
        x = np.interp(np.arange(m) * rate / 44100, np.arange(len(x)), x)
    return np.clip(np.round(x), -32768, 32767).astype(np.int16)


def c_bytes(name, data, kind="uint8_t"):
    items = [str(int(v)) for v in data]
    lines, line = [], ""
    for s in items:
        if len(line) + len(s) + 1 > 118:
            lines.append(line)
            line = ""
        line += s + ","
    lines.append(line)
    return f"static const {kind} {name}[{len(items)}] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("gif")
    ap.add_argument("wav")
    ap.add_argument("out")
    ap.add_argument("--seconds", type=float, default=1.5)
    ap.add_argument("--fps", type=int, default=25)
    a = ap.parse_args()
    fr, h = frames(a.gif, a.seconds, a.fps)
    if h > 240:
        raise SystemExit(f"{a.gif}: {h} rows at 240 wide: the screen has 240")
    fr = stabilise(fr)
    big = Image.fromarray(np.concatenate(fr, axis=0).astype(np.uint8))
    q = big.quantize(colors=NCOL, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:3 * NCOL]
    idx = np.asarray(q).reshape(len(fr), h, W).astype(np.uint8)
    blobs, prev = [], np.zeros((h, W), np.uint8)
    for f in idx:
        blobs.append(lz4blk.compress((f ^ prev).tobytes()))
        prev = f
    for b, f, p in zip(blobs, idx, [np.zeros((h, W), np.uint8)] + list(idx[:-1])):   # check the round trip
        assert lz4blk.decompress(b) == (f ^ p).tobytes()
    offs, o = [], 0
    for b in blobs:
        offs.append(o)
        o += len(b)
    offs.append(o)
    rgb565 = [((pal[3 * i] >> 3) << 11) | ((pal[3 * i + 1] >> 2) << 5) | (pal[3 * i + 2] >> 3) for i in range(NCOL)]
    snd = sound(a.wav)
    out = [f"/* Generated by tools/gen_splash.py from {Path(a.gif).name} and {Path(a.wav).name}: do not edit. */",
           "#pragma once", f"#define SPLASH_W {W}u", f"#define SPLASH_H {h}u", f"#define SPLASH_Y {(240 - h) // 2}u",
           f"#define SPLASH_FRAMES {len(blobs)}u", f"#define SPLASH_FRAME_MS {1000 // a.fps}u",
           f"#define SPLASH_SND_N {len(snd)}u", ""]
    body = c_bytes("SPLASH_PAL", rgb565, "uint16_t") + c_bytes("SPLASH_OFF", offs, "uint32_t") + \
        c_bytes("SPLASH_LZ4", b"".join(blobs)) + c_bytes("SPLASH_SND", snd, "int16_t")
    Path(a.out).write_text("\n".join(out) + body)
    print(f"splash: {len(blobs)} frames {W}x{h} at {a.fps} fps, {o} B; sound {len(snd)} samples "
          f"({len(snd) / 44100:.2f} s), {2 * len(snd)} B -> {a.out}")


if __name__ == "__main__":
    main()
