#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-only
// Reference audio from the bfxr2 JavaScript library, for checking the C port (bfxr_ref.c).
//   node gen_ref.js BFXR2_DIR OUT_DIR
// Writes OUT_DIR/case_NNNN.txt (33 numbers: the 32 Bfxr parameters in PARAMS order, then the
// render seed) and OUT_DIR/case_NNNN.f32 (the library's mono Float32 output), and
// OUT_DIR/akwf_tables.h (the three AKWF waves Bfxr uses, 256 x uint16 each).
'use strict';
const fs = require('fs');
const path = require('path');

const [, , bfxrDir, outDir] = process.argv;
if (!bfxrDir || !outDir) { console.error('usage: gen_ref.js BFXR2_DIR OUT_DIR'); process.exit(2); }
fs.mkdirSync(outDir, { recursive: true });

// The order of the 30 parameters in Bfxr.js param_info (the C port reads them in this order).
const PARAMS = ['waveType', 'masterVolume', 'attackTime', 'sustainTime', 'sustainPunch', 'decayTime',
  'compressionAmount', 'frequency_start', 'frequency_slide', 'frequency_acceleration',
  'min_frequency_relative_to_starting_frequency', 'vibratoDepth', 'vibratoSpeed',
  'pitch_jump_repeat_speed', 'pitch_jump_amount', 'pitch_jump_onset_percent', 'pitch_jump_2_amount',
  'pitch_jump_onset2_percent', 'overtones', 'overtoneFalloff', 'squareDuty', 'dutySweep', 'repeatSpeed',
  'flangerOffset', 'flangerSweep', 'lpFilterCutoff', 'lpFilterCutoffSweep', 'lpFilterResonance',
  'hpFilterCutoff', 'hpFilterCutoffSweep', 'bitCrush', 'bitCrushSweep'];

globalThis.window = globalThis;
(0, eval)(fs.readFileSync(path.join(bfxrDir, 'lib', 'bfxrlib.js'), 'utf8'));
const bfxr = globalThis.bfxr;

let n = 0, skipped = 0;
const presets = bfxr.presets('Bfxr');
for (const name of presets) {
  for (const seed of [12345, 777, 'a', 4242]) {
    for (let w = 0; w <= 11; w++) {
      const s = bfxr.preset('Bfxr', name, seed);
      s.params.waveType = w;
      let pcm;
      try { pcm = bfxr.render(s); } catch (e) { skipped++; continue; }
      if (!pcm || !pcm.length) { skipped++; continue; }
      const id = String(n++).padStart(4, '0');
      const nums = PARAMS.map(k => s.params[k]);
      if (nums.some(v => typeof v !== 'number')) throw new Error('missing param in ' + name);
      nums.push(s.renderSeed);
      fs.writeFileSync(path.join(outDir, `case_${id}.txt`), nums.map(v => v.toPrecision(17)).join('\n') + '\n');
      fs.writeFileSync(path.join(outDir, `case_${id}.f32`), Buffer.from(new Float32Array(pcm).buffer));
    }
  }
}
console.log(`${n} cases written, ${skipped} skipped`);

const akwf = fs.readFileSync(path.join(bfxrDir, 'js', 'audio', 'AKWF.js'), 'utf8');
let hdr = '/* Generated by gen_ref.js from bfxr2 js/audio/AKWF.js (Adventure Kid Waveforms, CC0). */\n';
for (const [key, cname] of [['granular_0044', 'AKWF_ORGAN'], ['fmsynth_0012', 'AKWF_FM'], ['hvoice_0012', 'AKWF_VOICE']]) {
  const m = akwf.match(new RegExp('static ' + key + ' = \\[([^\\]]*)\\]'));
  if (!m) throw new Error('AKWF ' + key + ' not found');
  const v = m[1].split(',').map(s => s.trim()).filter(Boolean).map(Number);
  if (v.length !== 256 || v.some(x => !(x >= 0 && x <= 65535 && Number.isInteger(x)))) throw new Error('bad table ' + key);
  hdr += `static const uint16_t ${cname}[256] = {${v.join(',')}};\n`;
}
fs.writeFileSync(path.join(outDir, 'akwf_tables.h'), hdr);
